"""Stage the LittleFS files and the build-selected firmware language."""

import shutil
from pathlib import Path


def stage_file_system(port_dir, board_name, language, staging_dir):
    if language not in ("zh", "en"):
        raise ValueError("Firmware language must be zh or en: {}".format(language))

    port_dir = Path(port_dir)
    staging_dir = Path(staging_dir)
    file_system_dir = port_dir / "file_system"
    sources = [file_system_dir / "common", file_system_dir / board_name]
    if language == "en":
        # The mpython_v3 English UI uses its product name as the directory.
        english_resource_name = "labplus_mpython_pro" if board_name == "mpython_v3" else board_name
        sources.append(port_dir / "en" / english_resource_name)

    for source in sources:
        if not source.is_dir():
            raise FileNotFoundError("File-system source directory not found: {}".format(source))

    staging_dir.mkdir(parents=True, exist_ok=True)
    for source in sources:
        shutil.copytree(str(source), str(staging_dir), dirs_exist_ok=True)

    # Generate this last so a resource overlay cannot silently override the
    # language chosen by MICROPY_LANGUAGE.
    language_module = staging_dir / "lib" / "firmware_language.py"
    language_module.parent.mkdir(parents=True, exist_ok=True)
    language_module.write_text(
        "# Generated by makeimg.py; do not edit.\n"
        "LANGUAGE = {!r}\n"
        "IS_ENGLISH = {!r}\n".format(language, language == "en"),
        encoding="utf-8",
    )
